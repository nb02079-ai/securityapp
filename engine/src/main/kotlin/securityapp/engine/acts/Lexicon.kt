package securityapp.engine.acts

/**
 * 행위 감지에 쓰는 표현 목록. 모두 정규화된 compact 형태(공백·기호 없음, 소문자)에서 찾는다.
 *
 * 출처 원칙 (docs/stage2_engine_design.md 1장)
 *  - 기준표 v2.1(docs/labeling/03_label_guide.md)의 정의·예시에 나온 말과, 일반적인 한국어 표현만 쓴다.
 *  - 평가 세트(data/eval/scam) 사례의 문장을 옮기지 않는다. 작성자가 평가 사례를 읽은 적이 있으므로,
 *    평가 사례에서만 본 표현(특정 직업·특정 핑계·특정 숫자 규칙 등)은 일부러 넣지 않았다.
 *    tools/scam/check_lexicon_leak.py로 평가 문장과의 겹침을 검사한다.
 *  - 규칙을 고칠 때는 개발 세트(data/dev)만 본다.
 */
internal object Lexicon {
    private fun r(vararg alts: String) = Regex(alts.joinToString("|"))

    // ── 공통 조각 ──
    /** 돈을 보내거나 넣는 동작 */
    const val SEND = "(보내|송금|입금|이체|넣어|넣으|넣고|넣는|넣을|충전|결제|지불|납부|내주|내줘|내셔|내시|내야|내면|내고)"

    // ── D 요구 ──
    /** D1 채널 이동: 다른 앱·방·사이트로 옮겨 오라, 가입·계정 등록 (기준표 D1) */
    val D1 = r(
        "(방|채팅방|단톡|단체방|오픈채팅|텔레그램|텔레|라인|사이트|홈페이지|앱|어플)(으로|로|에)(오세요|와주|와요|들어오|들어와|넘어오|넘어와|옮기|옮겨|이동|입장|접속)",
        "(회원가입|가입)(해주|해주세|해야|부터|하시고|하신후|하세요|해보세)",
        "계정(을|부터)?(만들|등록|개설|생성)",
        "(여기|이쪽)(서|에서)?(얘기|대화|이야기)(하기|하는)?(어려|곤란|힘들)",
    )
    /** D2 투자금 입금: 수익을 내려고 돈을 쓰라 (입금·충전, 내 계좌에서 특정 종목 매수 안내, 권유 포함) */
    val D2 = r(
        "(투자|매수|매입|참여|충전|입금)(해보세|해보시|하세요|해주세|하시면|하셔야|해봐|할래|하실래|하시겠)",
        "(넣어|사|사두|사놓|담아)(보세요|두세요|놓으세요|세요|봐요|보실래|볼래)",
        "(소액|조금)(으로|만|이라도)?(시작|해보|넣어|투자)",
        "(매수|사세요|사두세요|담으세요)",
        "(투자금|참여금|입금액|증거금)",
        "${SEND}(하시면|하면)(수익|환급|배당|두배)",
    )
    /** 매도만 말하는 안내는 D2가 아님 (기준표 D2 "붙이지 않는 경우") */
    val D2_SELL = Regex("(매도|팔아|파세요|파시|익절|손절)")
    val D2_BUY = Regex("(매수|사세요|사두|사놓|담아|넣어|투자|충전|입금|참여)")

    /** D3 대납·차용: 상대 사정으로 내 달라, 빌려 달라, 대신 보내 달라 (이자·수수료 약속이 있어도) */
    val D3 = r(
        "(빌려|꿔|빌릴|빌리)",
        "대신(내|지불|결제|보내|송금|입금|납부)",
        "(대납|선결제)",
        "(통관비|배송비|관세|운송비|병원비|수술비|급전)",
        "(갚을게|갚겠|갚아드|돌려줄게|돌려드릴게)",
        "이자(를)?(줄게|드릴게|쳐서|붙)",
    )
    /** D4 지정 계좌·경로 통제: 보낼 곳·방법을 지정하거나 제한함 */
    val D4 = r(
        "(계좌|지갑|지갑주소)(로|에|번호로)${SEND}",
        "(이|해당|지정|전용)(계좌|지갑)",
        "(계좌번호|지갑주소)",
        "(atm|에이티엠|무통장)(으로|로)?만",
        "창구(는|말고|에서는|이용은)?(금지|안됩|안되|하지마|쓰지마|말고|가지마)",
        "(은행|직원|창구)(에|에게|한테)(는)?(이유|사유|용도)?(를)?(말하지|얘기하지|알리지|밝히지)",
        "(송금|입금)사유",
    )
    /** 실제 알림에 나올 수 있는 계좌번호·지갑 주소 모양 (원래 문장에서 찾음) */
    val D4_ACCOUNT_SHAPE = Regex("(\\d{2,6}-\\d{2,6}-\\d{2,8}(-\\d{1,6})?|0x[0-9a-fA-F]{30,}|\\b(bc1|[13])[a-zA-HJ-NP-Z0-9]{25,}\\b|\\bT[1-9A-HJ-NP-Za-km-z]{33}\\b)")

    /** D5 출금 조건부 추가 입금: 이미 넣은 돈을 빼려면 더 내라 */
    val D5 = r(
        "(출금|인출|환급|빼려|빼시려|빼실|돌려받으)(하려면|려면|하시려면|하기위해|하기전에|을위해)",
        "(출금|인출|환급)(수수료|세금|보증금|조건)",
        "(출금|인출|빼|찾)(.{0,10})(더|추가|먼저|선)(입금|납부|내|투자|충전)",
        "(더|추가)(입금|납부|투자|충전)(해야|하셔야|하면)(.{0,6})(출금|인출|빼|찾)",
    )
    /** D6 비밀 유지·고립: 가족·은행에 말하지 마라, 거짓말을 하라 */
    val D6 = r(
        "(비밀|기밀)(로|을|를|은)?(유지|지켜|해주|해야)",
        "(말하지|알리지|얘기하지|말씀하지)(마|말아|마세요|말고|마시)",
        "(가족|남편|아내|부모|자녀|지인|은행|친구)(분)?(들)?(에게|한테|께)(는|도)?(비밀|모르게|말하지|숨기|알리지|나중에)",
        "(모르게|숨기세요|숨겨주|거짓말|둘만알|우리둘만|우리만알)",
        "(가족|남편|아내|부모|자녀|지인|친구)(분)?(들)?(에게|한테|께)(는)?(.{0,10})(나고|되면|된뒤|난뒤|후에|다음에)(말씀|얘기|알리)",
    )
    /** D7 개인정보 요구·앱 설치: "나"에게 정보를 달라 */
    const val D7_NOUN = "(신분증|주민등록|주민번호|여권|운전면허|인증번호|otp|비밀번호|공인인증|계좌번호|카드번호|주소|전화번호|휴대폰번호|휴대전화번호|연락처|계정정보|아이디)"
    val D7 = r(
        "${D7_NOUN}(사진)?(을|를|좀|도|과|와|이랑)?(.{0,10})(보내주|보내줘|알려주|알려줘|남겨주|올려주|찍어보내|부탁드|필요합|주세요|입력해)",
        "(앱|어플|프로그램|apk)(을|를)?(설치|깔아|다운받)",
        "(팀뷰어|애니데스크|원격제어|원격지원|원격접속)",
    )
    /** 손실·투자 금액을 알려 달라는 것은 D7이 아님 (기준표 v2.1) */
    val D7_AMOUNT_ONLY = Regex("(손실|투자|피해|넣은)(금액|액수)")

    // ── P 설득 ──
    /** P1 수익 보장·위험 부정 */
    val P1 = r(
        "(원금|수익|이익)(을|은|이)?(보장|확정|보전)",
        "(무조건|반드시|확실히|틀림없이)(오르|올라|수익|벌|번다|남)",
        "(손해|손실|리스크|위험)(볼일|날일|는|가)?(없|제로)",
        "손실(을|은)?(보상|보전|메워|채워)",
        "(한달|매달|매월|하루|일주일|월)(에)?(최소|평균|기본)?[0-9]+(%|퍼센트|프로)",
        "[0-9]+(%|퍼센트|프로)(는)?(기본|이상|확정|보장)",
        "(언제든|언제든지)(출금|인출|뺄|빼|환불)",
        "수익률",
        "(수익|대박)(확실|보장|장담)",
    )
    /** "~할 수도 있다" 수준, 다른 사람이 벌었다는 이야기만 있는 것은 P1이 아님 */
    val P1_HEDGE = Regex("(수도있|일수도|가능성|장담못|보장못|보장은못)")

    /** P2 권위·신분 과시: 특정 직업·지위·기관을 내세우거나 증명서·서류로 믿게 함 */
    val P2 = r(
        "(전문가|애널리스트|교수|박사|ceo|회장|원장|펀드매니저|트레이더|의사|변호사|연구원)(입니다|이에요|예요|이고|출신|님이|께서|으로서|로서|로일|으로일)",
        "(증권사|은행|금융감독원|금감원|검찰|경찰|수사관|국세청|공공기관|협회|거래소)(에서|의)?(인증|공식|직접|소속|출신|담당|승인)",
        "(출신|경력|자격증|라이선스|인가받|등록업체|정식업체|공식업체)",
        "(에서|로|으로)일하(고있|는)",
        "(사원증|신분증|면허증|증명서|계약서|인증서|재직증명|서류)(사진)?(이에요|입니다|보내드|보여드|첨부|드릴게|드려요|올려드|찍어서보낼|보낼게)",
    )
    /** P3 긴급성·한정성: 오늘까지, 마지막, 몇 명만·회원만, 급한 사정 */
    val P3 = r(
        "(오늘|이번주|이번달|내일|금일)(까지|만|중으로|안에|마감)",
        "(지금|당장)(아니면|안하면|해야|하셔야|신청|결정|입금|참여)",
        "(마감|선착순|한정|마지막|막차|조기종료|조기마감)",
        "[0-9]+(명|분|자리)(만|한정|선착순|남았)",
        "(회원|우수회원|vip|선택된분)(님)?(들)?(에게|께|한테)?만",
        "(급한사정|급해요|급하게|급히|시간이없|놓치면|서두르)",
    )
    /** P4 만남·확인 회피: 영상통화·만남·확인을 미루거나 핑계를 댐 */
    val P4 = r(
        "(영상통화|화상통화|카메라|만나|만남|직접확인)(는|은|가|이)?(.{0,10})(안돼|안되|못해|못하|어렵|고장|안터|불가|다음에|나중에|미뤄|미루|취소|힘들)",
    )

    // ── G 진행 ──
    /** G1 소액 선보상: 상대가 "나"에게 실제로 줬다고 알림 */
    val G1 = r(
        "(입금|송금|지급|충전|환급|적립)(해드렸|해드렸습|됐습|되었습|됐어요|되었어요|완료)",
        "(보내드렸|넣어드렸|쏴드렸)",
        "(수익금|보상금|축하금|지원금|환급금|선물|사례금)(을|이)?(보냈|입금|지급|들어갔|도착)",
        "(통장|계좌)(보시면|확인해보시면|에들어)",
    )
    /** 앞으로 주겠다는 약속은 G1이 아님 (→ P1) */
    val G1_FUTURE = Regex("(드릴게|드리겠|줄게|주겠|해드릴|보내드릴|예정)")

    /** G3 요구 금액 증가: 대출 권유, 큰 금액일수록 유리한 규칙 (앞 금액과의 비교는 맥락에서) */
    val G3_LOAN = r("(대출|카드론|마이너스통장|빚내|빌려서라도|담보)")
    val G3_TIER = r(
        "(금액|투자금|액수)(이|을)?(클수록|많을수록|커야|늘려)",
        "(등급|레벨)(이|을|가)?(올라|올리|상승)",
        "이상(넣|투자|입금)(어야|해야|하셔야)",
        "(금액|투자금)을?(늘|올)(려|리)",
    )

    /** G4 요구 반복: "나"의 거절·망설임 뒤 붙잡음 (기준표 예시: "지금 그만두면 넣은 돈도 다 날아가요") */
    val G4 = r(
        "(그만두면|포기하면|포기하지마|중단하면|지금빼면|지금나가면)",
        "(한번만더|이번만)",
        "(그러지말고|그러지마세요)",
    )
    /** "나"의 거절·망설임 (평가용 재생에서만 들어옴) */
    val USER_REFUSAL = r(
        "(싫어|싫습|안할래|안할게|못하겠|안하겠|그만할|그만하고|그만둘|위험할|의심|거절|생각해볼|나중에할|여유가없|돈이없)",
    )

    // ── R 관계 ──
    /** R1 단체방 맞장구: 다른 회원이 수익 인증·감사·참여 의사로 분위기를 띄움 */
    val R1 = r(
        "(감사합니다|감사해요|고맙습니다|덕분에|최고|대박)",
        "(수익|익절|벌었|올랐|들어왔|받았|인증|성공)",
        "(저도|나도)(참여|들어가|들어갔|했|넣|따라|시작|받)",
        "(참여합니다|참여할게|함께합니다)",
    )
    /** R2 친밀감 쌓기: 안부·호의·칭찬, 짧은 기간의 사랑·운명 표현 */
    val R2 = r(
        "(식사|밥|점심|저녁|아침)(은|는)?(드셨|먹었|하셨|맛있게)",
        "(잘잤|잘자요|좋은꿈)",
        "(보고싶|그리워|사랑해|사랑합|운명|자기야|당신같은|너같은|특별한사람)",
        "(건강챙|조심하세요|걱정돼|걱정되|힘내세요|힘내요|응원해)",
        "(믿어요|믿습니다|믿을게요)$",
    )

    /** 돈 이야기 낌새 (G2: 이 메시지에서 돈 이야기로 넘어갔는지) */
    val MONEY_WORDS = r("(돈|투자|수익|코인|주식|비트|입금|송금|계좌|원금|대출|만원|억|수수료|배송비|통관|이자|환급)")
}
